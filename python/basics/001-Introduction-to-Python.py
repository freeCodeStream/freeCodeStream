# 001-Introduction-to-Python

# Python is a great first programming language, and even if you already know another language,
# learning Python is a valuable skill. It is easy to learn, highly versatile, and widely used in web development,
# data analysis, automation, and more.


# 1. Installing Python
# To start coding in Python, you need to install it on your computer:
# - Visit [python.org](https://www.python.org/) and download the latest version for your operating system.
# - If you are using Windows 7 or older, you may need to download an older Python version from the site.


# 2. Installing a Code Editor
# A code editor helps you write and manage your Python programs easily.
# A good choice is Visual Studio Code (VS Code).
    # - Download it from [code.visualstudio.com](https://code.visualstudio.com/).
    # - After installing, open VS Code and install the Python extension from Microsoft.
    #   This helps with syntax highlighting, debugging, and running Python code.


# 3. Setting Up Python in VS Code
# Once you have Python and VS Code installed, follow these steps:

# - Open VS Code and create a new folder for your Python projects.
# - Open the Command Palette by pressing `Ctrl + Shift + P` (or `Cmd + Shift + P` on Mac) and
#       type `Python: Select Interpreter`. Choose the installed Python version.
# - Open the Terminal and verify your installation by typing:
#   - On Windows: `py --version`
#   - On Mac/Linux: `python3 --version`

# 4. Writing and Running Your First Python Program
# - Create a new file in VS Code and name it hello.py.
# - Write the following code:

greeting = "Hello, World!"
print(greeting)

# - Save the file (`Ctrl + S` or `Cmd + S` on Mac).
# - Run the file in one of three ways:
#   1. Click the Run button in VS Code.
#   2. Open the terminal and type:
#      - Windows: `py hello.py`
#      - Mac/Linux: `python3 hello.py`
#   3. Right-click the file in the Explorer panel and select Run Python File in Terminal.



# 5. Understanding Python REPL
# - Python has an interactive mode called REPL (Read-Evaluate-Print Loop).
# - Open the terminal and type `py` (Windows) or `python3` (Mac/Linux) to enter REPL.
# - You can test Python commands directly, like:
# example:

2 + 2   # - This will output `4`.

# - Exit REPL by typing `quit()` and pressing Enter.

# 6. Next Steps
# Now that you have set up Python and run your first program, you are ready to dive deeper into Python programming.
# Keep practicing and remember:
# - Practice daily – small progress every day leads to mastery.
# - Don’t fear mistakes – debugging helps you learn.
# - Ask questions – join Python communities for support.

